// Regenerates src/ui/appIcons.js from the Iconify JSON packages (devDependencies):
//   Fluent UI System Color Icons (MIT, Microsoft) and Flat Color Icons (MIT, Icons8).
// Only the icons the in-game desktops use are copied, so the game bundle stays small.
//   node scripts/gen-app-icons.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const sets = {
  fluent: require('@iconify-json/fluent-color/icons.json'),
  flat: require('@iconify-json/flat-color-icons/icons.json'),
};

// app id → [set, icon name]
const MAP = {
  phone: ['flat', 'phone'],
  remote: ['fluent', 'phone-laptop-32'],
  notes: ['fluent', 'notebook-32'],
  browser: ['fluent', 'globe-24'],
  cashier: ['fluent', 'savings-32'],
  playbook: ['fluent', 'book-open-48'],
  messenger: ['fluent', 'people-chat-48'],
  files: ['flat', 'opened-folder'],
  antivirus: ['fluent', 'shield-checkmark-48'],
  recorder: ['flat', 'camcorder-pro'],
  paint: ['fluent', 'paint-brush-32'],
  camera: ['flat', 'compact-camera'],
  docforge: ['fluent', 'document-edit-24'],
  siteforge: ['fluent', 'code-block-48'],
  mycomputer: ['flat', 'folder'],
  cmd: ['flat', 'command-line'],
  eventvwr: ['fluent', 'warning-48'],
  notepad: ['fluent', 'document-text-48'],
  recycle: ['flat', 'empty-trash'],
  obs: ['flat', 'video-call'],
  vbox: ['flat', 'org-unit'],
  user: ['fluent', 'person-48'],
  // scam earner apps
  giftcards: ['fluent', 'gift-card-24'],
  creditcard: ['flat', 'money-transfer'],
  identity: ['fluent', 'contact-card-48'],
};

const out = {};
for (const [id, [set, name]] of Object.entries(MAP)) {
  const data = sets[set];
  const icon = data.icons[name];
  if (!icon) throw new Error(`missing ${set}:${name}`);
  const w = icon.width || data.width || 16;
  const h = icon.height || data.height || 16;
  out[id] = { w, h, body: icon.body };
}

const src = `// GENERATED by scripts/gen-app-icons.mjs — do not edit by hand.
// Colour app icons: Fluent UI System Color Icons (MIT, © Microsoft) and
// Flat Color Icons (MIT, © Icons8), via Iconify.
export const APP_ICONS = ${JSON.stringify(out, null, 0)};
`;
writeFileSync(new URL('../src/ui/appIcons.js', import.meta.url), src);
console.log(`wrote ${Object.keys(out).length} icons, ${src.length} bytes`);
